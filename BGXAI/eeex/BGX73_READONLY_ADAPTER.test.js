'use strict';
const assert=require('node:assert/strict');
const A=require('./BGX73_READONLY_ADAPTER.js');
let num=0;function t(a,b,msg){assert.deepEqual(a,b,msg);num++}
const line='[BGX73] OBS actor=A2 slot=4 class=7 kit=2000 level=3/2/0 hp=25 enemyLOS=2 selected=leader BDAI=0,1,0,0,1,2,2,0 manual=? trap=? path=? identity=SESSION_ONLY';
const e=A.parse(line);
t(!!e,true,'parse');t(e.alias,'A2','actor');t(e.slot,4,'slot');t(e.classCode,7,'class');t(e.kitCode,2000,'kit');t(e.levels,[3,2,0],'levels');t(e.hpRaw,25,'hp');t(e.hostilesLOS,2,'visible threats');
t(e.selectedLeader,true,'selected');t(e.locals.BDAI_SKILL_MODE,2,'local skill');t(e.locals.BDAI_DISABLE_ITEMS,1,'items blocked');
t(e.identityScope,'process-session-only','non-persistent');t(e.manualStatus,'UNKNOWN','not inferred');
const partial=A.toScoutSnapshot(e,{saveEpoch:'mock_save_load_epoch',monotonicMs:10000});
t(partial.valid,true,'valid');t(partial.actorKey,'session:A2','key scope');
t(partial.visibleHostiles[0].hostile,true,'enemy evidence');t(partial.surroundingsChecked,false,'no 360 clearance');
t(partial.visibilitySnapshotFresh,false,'throttled log cannot be current sensor');
t(partial.mayDisarm,false,'fail closed disarm');t(partial.mayRetreat,false,'fail closed retreat');
t(partial.canDisarm,false,'not inferred from class');t(partial.safeRetreatToParty,false,'no path proof');
const noEnemy=A.parse(line.replace('enemyLOS=2','enemyLOS=0'));
t(A.toScoutSnapshot(noEnemy,{saveEpoch:'e',monotonicMs:5}).visibleHostiles.length,0,'zero enemies');
t(A.toScoutSnapshot(noEnemy,{saveEpoch:'e',monotonicMs:5}).surroundingsChecked,false,'zero not safety');
const unknown=A.parse(line.replace('enemyLOS=2','enemyLOS=?'));
t(unknown.hostilesLOS,null,'unknown hostiles');t(A.toScoutSnapshot(unknown,{saveEpoch:'e',monotonicMs:5}).visibleHostiles,null,'unknown list');
t(A.parse('random'),null,'ignore other lines');t(A.parse(line.replace('actor=A2','actor=Imoen')),null,'no name identity');
t(A.parse(line.replace('slot=4','slot=9')),null,'invalid slot');
t(A.parse(line.replace('manual=?','manual=0')),null,'manual unproven');
t(A.parse(line.replace('identity=SESSION_ONLY','identity=GUARANTEED')),null,'identity spoof');
t(A.toScoutSnapshot(e,{saveEpoch:'',monotonicMs:4}).valid,false,'epoch needed');
t(A.toScoutSnapshot(e,{saveEpoch:'s',monotonicMs:-3}).valid,false,'valid time needed');
console.log(`PASS ${num} read-only adapter tests`);
const fs=require('node:fs'), path=require('node:path');
const relativeScout=fs.existsSync(path.join(__dirname,'../scout/BGX_SCOUT_SAFETY_V01.js'))
 ? '../scout/BGX_SCOUT_SAFETY_V01.js' : './BGX_SCOUT_SAFETY_V01.js';
const S=require(relativeScout);
const d=S.step(null,partial);
assert.notEqual(d.kind,'DISARM_TRAP','unverified EEex observation can never disarm');
const z=A.toScoutSnapshot(noEnemy,{saveEpoch:'s',monotonicMs:20});
assert.notEqual(S.step(null,z).kind,'DISARM_TRAP','zero visible enemies cannot authorize disarm');
console.log('PASS scout safety fail-closed integration (2)');