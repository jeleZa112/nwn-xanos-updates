const assert=require('node:assert/strict');
const x=require('./BDDEFAI_CONFIG_BRIDGE_V01.js');
let count=0;
function test(name,actual,expected){assert.strictEqual(actual,expected,name);count++;}
const flags={"LOCALSBDAI_DISABLE_ATTACK":0,"LOCALSBDAI_ATTACK_MODE":2,"LOCALSBDAI_DISABLE_ITEMS":1,"LOCALSBDAI_SKILL_MODE":1,"LOCALSBDAI_DISABLE_DEFENSIVE":0,"LOCALSBDAI_DISABLE_OFFENSIVE":1,"LOCALSBDAI_DISABLE_SPECIAL":0,"LOCALSBDAI_NO_ARCANE":1};
const cap=Object.fromEntries(x.MAPPED_TASKS.map(k=>[k,true]));
const p=x.importBDAI(flags,cap,{});
test('attack melee',p.enabled.melee,true);
test('attack ranged',p.enabled.ranged,true);
test('ranged preference',p.attackPreference,'ranged_when_safe');
test('potion denied',p.enabled.healingItem,false);
test('wand denied',p.enabled.wand,false);
test('defense allowed',p.enabled.defenseSpell,true);
test('offense denied',p.enabled.damageSpell,false);
test('skill detect selected',p.selectedLegacyMode,'detect');
test('other skills unspecified',p.requested.hide,undefined);
test('lawful arcane restriction',p.noArcaneContext,true);
test('special permitted',p.specialPermitted,true);
test('special items denied',p.enabled.specialItem,false);
test('independent hide',x.importBDAI(flags,cap,{hide:true}).enabled.hide,true);
test('independent offense',x.importBDAI(flags,cap,{damageSpell:true}).enabled.damageSpell,true);
test('kit restriction',x.importBDAI(flags,{...cap,damageSpell:false},{damageSpell:true}).enabled.damageSpell,false);
test('manual override',x.selectModal({manualOrder:true,combat:true,canSingNow:true,songExpectedUseful:true},{song:true}),'HOLD');
test('trap scan priority',x.selectModal({safeIdle:true,trapRisk:true,canDetectNow:true,stealthMode:true,canHideNow:true},{detect:true,hide:true}),'DETECT_TRAPS');
test('stealth priority',x.selectModal({safeIdle:true,trapRisk:false,canDetectNow:true,stealthMode:true,canHideNow:true},{detect:true,hide:true}),'HIDE');
test('hidden holds',x.selectModal({hidden:true,safeIdle:true,trapRisk:true,canDetectNow:true},{detect:true}),'HOLD');
test('turns undead first',x.selectModal({combat:true,undeadVisible:true,canTurnNow:true,turnExpectedUseful:true,canSingNow:true,songExpectedUseful:true},{turnUndead:true,song:true}),'TURN_UNDEAD');
test('combat song',x.selectModal({combat:true,canSingNow:true,songExpectedUseful:true},{song:true}),'SING');
test('no turn without undead',x.selectModal({combat:true,canTurnNow:true,turnExpectedUseful:true},{turnUndead:true}),'HOLD');
test('retain song',x.selectModal({combat:true,activeModal:'song',canSingNow:true,songExpectedUseful:true},{song:true}),'KEEP_SONG');
test('unrecognized flag disabled',x.importBDAI({"BDAI_DISABLE_ATTACK":"?"},cap,{}).enabled.ranged,false);
test('turn undead imported',x.importBDAI({"BDAI_SKILL_MODE":4},cap,{}).enabled.turnUndead,true);
test('inactive dual skill blocked',x.importBDAI({"BDAI_SKILL_MODE":1},{...cap,detect:false},{}).enabled.detect,false);
test('user override disables ranged',x.importBDAI(flags,cap,{ranged:false}).enabled.ranged,false);
test('melee-only legacy',x.importBDAI({"BDAI_DISABLE_ATTACK":0,"BDAI_ATTACK_MODE":1},cap,{}).enabled.ranged,false);
test('arbitrary number of actors',x.importBDAI(flags,cap,{}).source,'user_BDDEFAI_BCS_variables');
console.log('PASS '+count+' BDDEFAI compatibility cases');
