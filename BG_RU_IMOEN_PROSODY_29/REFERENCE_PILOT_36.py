"""BG Voice RU 3.6: real A/B Russian speech generation with per-part voice refs.

English laugh is reused as an audio event; Russian PARTS generated by the
already installed local Qwen. This is reference comparison, NOT automatic
English-to-Russian intonation transfer. Existing WAVs are never replaced.
"""
from pathlib import Path
from math import gcd
import argparse
import csv
import hashlib
import html
import os
import sys
import time
import wave

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
MODEL = ROOT / '.tools' / 'models' / 'qwen3-ru-stress-cf'
EN = ROOT / 'RVC_DATASETS' / 'IMOEN' / 'IMOEN77A.wav'
REF_SHORT = ROOT / 'BG_RU_RASK75_CLONE_24' / 'RASK01_SHORT.wav'
LONG_CANDIDATES = [
    ROOT / 'BG_RU_RASK75_CLONE_24' / 'RASK75_LONG.wav',
    ROOT / 'BG_RU_IMOEN_BATCH_26' / 'RASK75_LONG.wav',
]
PREVIOUS = HERE / 'OUTPUT_LAUGH_35' / 'IMOEN77A_EN_LAUGH_RU_PARTS_35.wav'
OUT = HERE / 'OUTPUT_REFERENCE_36'
CACHE = OUT / 'PARTS'
LOG = HERE / 'REFERENCE_36_RUN.log'
PAGE = HERE / 'LISTEN_REFERENCE_36.html'
ID = 'IMOEN77A'
PARTS = (
    ('greeting', 'Приятно снова встретить тебя, маленький братец.'),
    ('playful', 'Мне нравится так тебя называть.'),
    ('question', 'Ну, ты готов идти?'),
    ('request', 'Мне бы хотелось путешествовать с тобой, если можно.'),
)
FULL_TEXT = ' '.join((PARTS[0][1], 'Ха!', PARTS[1][1], PARTS[2][1], PARTS[3][1]))
# All timing positions in original English source (auditionable, not phoneme aligned).
LAUGH_RANGE = (2.42, 2.91)
REFS = {'BRIGHT': REF_SHORT}


def log(msg):
    s = time.strftime('%H:%M:%S') + ' ' + str(msg)
    print(s, flush=True)
    with LOG.open('a', encoding='utf-8') as f:
        f.write(s + '\n')


def duration(path):
    try:
        with wave.open(str(path), 'rb') as f:
            return f.getnframes() / f.getframerate()
    except (OSError, ValueError, EOFError, wave.Error, ZeroDivisionError):
        return 0


def get_long():
    for f in LONG_CANDIDATES:
        if 15.0 <= duration(f) <= 35.0:
            return f
    raise RuntimeError('Rask75_LONG.wav unavailable in existing local 2.4 / 2.6 folders')


def check_text():
    src = ROOT / 'VOICE_MANIFEST.csv'
    if not src.exists():
        raise FileNotFoundError('VOICE_MANIFEST.csv missing in root; no invented translation')
    with src.open(encoding='utf-8-sig', newline='') as f:
        rows = [r for r in csv.DictReader(f) if (r.get('Resource') or '').strip().upper() == ID]
    if len(rows) != 1 or (rows[0].get('Character') or '').strip().upper() != 'IMOEN':
        raise RuntimeError('Manifest character/resource mismatch for IMOEN77A')
    actual = (rows[0].get('Russian_existing') or '').split(' | ')[0].strip()
    if actual != FULL_TEXT:
        raise RuntimeError('Manifest exact text differs: manual review needed; manifest=' + repr(actual))


def preflight(check_model=True):
    check_text()
    if not 3 <= duration(REF_SHORT) <= 7:
        raise RuntimeError('Missing RASK01_SHORT.wav in ' + str(REF_SHORT))
    long = get_long()
    if not 8 <= duration(EN) <= 15:
        raise RuntimeError('English IMOEN77A.wav missing or invalid')
    if check_model:
        for name in ('config.json', 'model.safetensors', 'speech_tokenizer/model.safetensors'):
            if not (MODEL / name).is_file():
                raise RuntimeError('Existing Qwen cached model missing ' + name + '; no download performed')
    REFS['SOFT'] = long
    OUT.mkdir(exist_ok=True)
    CACHE.mkdir(exist_ok=True)
    log('CHECK OK: Rask01=%.2fs, Rask75=%.2fs, English=%.2fs; exact manifest text' %
        (duration(REF_SHORT), duration(long), duration(EN)))
    log('OUTPUT is separate; approved B_LONG_XVECTOR and older Russian WAVs will not be modified')


def read(path):
    import numpy as np
    import soundfile as sf
    data, sr = sf.read(str(path), dtype='float32', always_2d=True)
    if not len(data) or sr < 8000:
        raise ValueError('Invalid WAV ' + str(path))
    return np.mean(data, axis=1).astype('float32'), int(sr)


def save(path, data, sr):
    import numpy as np
    import soundfile as sf
    v = np.asarray(data, dtype='float32').squeeze()
    if v.ndim != 1 or not np.isfinite(v).all() or not .2 < len(v) / sr < 60:
        raise RuntimeError('Invalid model output; not saving')
    peak = float(np.max(np.abs(v)))
    if peak < .006:
        raise RuntimeError('Output essentially silent')
    if peak > .97:
        v = v * (.95 / peak)
    if path.exists():
        if duration(path) > .3:
            log('KEEP ' + path.name)
            return
        raise RuntimeError('Existing invalid WAV not overwritten: ' + str(path))
    tmp = path.with_name(path.name + '.partial.wav')
    if tmp.exists():
        raise RuntimeError('Unfinished partial WAV detected: ' + str(tmp))
    try:
        sf.write(str(tmp), v, sr, subtype='PCM_16')
        if not .2 < duration(tmp) < 60:
            raise RuntimeError('Saved WAV failed readback')
        # Refuse replacement even if multiple process instances run concurrently.
        with tmp.open('rb') as source, path.open('xb') as target:
            while True:
                block = source.read(1024 * 1024)
                if not block:
                    break
                target.write(block)
    finally:
        if tmp.exists():
            tmp.unlink()


def trim_silence(v, sr):
    import numpy as np
    # Remove only far-edge digital silence; not internal pauses/expressive breaths.
    w = max(1, int(sr * 0.02))
    n = len(v) // w
    if n < 3:
        return v
    e = np.array([np.sqrt(np.mean(v[i*w:(i+1)*w]**2)) for i in range(n)])
    threshold = max(.0005, min(.009, float(np.max(e)) * .07))
    active = np.flatnonzero(e > threshold)
    if len(active) == 0:
        return v
    left = max(0, int(active[0]) * w - int(sr * .05))
    right = min(len(v), int(active[-1] + 1) * w + int(sr * .09))
    return v[left:right]


def fade(v, sr, ms=10):
    import numpy as np
    v = v.copy()
    n = min(int(sr * ms / 1000), len(v) // 4)
    if n > 2:
        v[:n] *= np.linspace(0, 1, n, dtype='float32')
        v[-n:] *= np.linspace(1, 0, n, dtype='float32')
    return v


def reference_output_path(label, key):
    return CACHE / (ID + '_' + key + '_' + label + '_XVECTOR_36.wav')


def get_or_generate(model, torch, label, key, text):
    p = reference_output_path(label, key)
    if duration(p) > .3:
        log('KEEP ' + p.name)
        return p
    if p.exists():
        raise RuntimeError('Invalid previous WAV: ' + str(p))
    ref = REFS[label]
    seed = 36000 + int(hashlib.sha256((key + label).encode('utf8')).hexdigest()[:7], 16) % 100000
    torch.manual_seed(seed)
    log('GENERATE ' + key + ' with ' + label + ' reference: ' + text)
    with torch.inference_mode():
        audio, sr = model.generate_voice_clone(text=text, language='Russian',
            ref_audio=str(ref), ref_text=None, x_vector_only_mode=True,
            max_new_tokens=2600)
    if len(audio) != 1:
        raise RuntimeError('Unexpected model batch size')
    save(p, audio[0], int(sr))
    return p


def compose(name, selection):
    import numpy as np
    from scipy.signal import resample_poly
    output = OUT / (ID + '_' + name + '_36.wav')
    if duration(output) > 2:
        log('KEEP ' + output.name)
        return
    if output.exists():
        raise RuntimeError('Invalid existing composite not overwritten: ' + str(output))
    paths = [reference_output_path(ref, key) for (key, _), ref in zip(PARTS, selection)]
    chunks = [read(p) for p in paths]
    rsr = chunks[0][1]
    if any(sr != rsr for a, sr in chunks):
        raise RuntimeError('Different Qwen sample rates; safely abort')
    en, esr = read(EN)
    laugh = en[int(LAUGH_RANGE[0] * esr):int(LAUGH_RANGE[1] * esr)]
    if esr != rsr:
        g = __import__('math').gcd(esr, rsr)
        laugh = resample_poly(laugh, rsr // g, esr // g).astype('float32')
    if len(laugh) < .3 * rsr:
        raise RuntimeError('Original laugh range is too short')
    a = [fade(trim_silence(v, rsr), rsr) for v, _ in chunks]
    laugh = fade(laugh, rsr, 8)
    pause = lambda ms: np.zeros(int(rsr * ms / 1000), dtype='float32')
    # Explicit semantic speech parts; preserves laughter from original game.
    result = np.concatenate([a[0], pause(130), laugh, pause(90), a[1], pause(160),
                             a[2], pause(180), a[3]])
    peak = float(np.max(np.abs(result)))
    if peak > .95:
        result *= .93 / peak
    save(output, result, rsr)
    log('DONE ' + output.name + ' %.2fs' % duration(output))


def page():
    def link(path):
        return html.escape(os.path.relpath(str(path), str(HERE)).replace('\\', '/'), quote=True)
    clips = [
        ('Английский оригинал — настроение и интонация', EN),
        ('Утверждённый предыдущий монтаж 3.5', PREVIOUS),
        ('A. BRIGHT: все смысловые части с Rask01', OUT / (ID + '_BRIGHT_ALL_36.wav')),
        ('B. MIX: Rask01 для весёлых частей, Rask75 для просьбы', OUT / (ID + '_MIX_36.wav')),
        ('Образец Rask01: более звонкий', REF_SHORT),
        ('Образец Rask75: более мягкий', REFS.get('SOFT', LONG_CANDIDATES[0])),
    ]
    content = ['<!doctype html><html lang="ru"><meta charset="utf-8"><title>BG Voice RU 3.6 — эталоны Имоуэн</title>',
               '<style>body{font:16px system-ui;max-width:900px;margin:24px auto;padding:16px}section{border:1px solid #bbb;padding:14px;border-radius:12px;margin:12px 0}audio{display:block;width:100%;margin:8px 0}</style>',
               '<h1>Имоуэн IMOEN77A: звонкий против смешанного голоса</h1>',
               '<p>Настоящий смех из английского оригинала одинаков в обоих вариантах. Звучание остальной речи определяется выбранным образцом; контур английской интонации пока НЕ переносится автоматически.</p>',
               '<p>' + html.escape(FULL_TEXT) + '</p>']
    for label, path in clips:
        content.append('<section><b>' + html.escape(label) + '</b>')
        if duration(path) > .3:
            content.append('<audio controls preload="none" src="' + link(path) + '"></audio>')
        else:
            content.append('<p>Файл отсутствует или ещё не сгенерирован</p>')
        content.append('</section>')
    content.append('<p>Обязательно проверить: «путешествовать с тобой» без повторов; звонкость вопроса; сходство тембра; переход от смеха к словам.</p></html>')
    PAGE.write_text(''.join(content), encoding='utf8')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    preflight()
    page()
    if args.check:
        return 0
    import torch
    if not torch.cuda.is_available():
        raise RuntimeError('CUDA not available. Existing environment and WAVs unchanged.')
    from qwen_tts import Qwen3TTSModel
    log('LOADING existing cached Qwen RU-Stress Base. No downloads/install.')
    model = Qwen3TTSModel.from_pretrained(str(MODEL), device_map='cuda:0',
                                         dtype=torch.bfloat16, attn_implementation='sdpa')
    errors = []
    for key, text in PARTS:
        for label in (('BRIGHT', 'SOFT') if key == 'request' else ('BRIGHT',)):
            try:
                get_or_generate(model, torch, label, key, text)
            except Exception as e:
                log('FAILED ' + key + ' ' + label + ': ' + repr(e))
                errors.append(key + '/' + label)
    if errors:
        log('GENERATION INCOMPLETE: ' + ', '.join(errors))
        page()
        return 2
    compose('BRIGHT_ALL', ['BRIGHT', 'BRIGHT', 'BRIGHT', 'BRIGHT'])
    compose('MIX', ['BRIGHT', 'BRIGHT', 'BRIGHT', 'SOFT'])
    page()
    log('SUCCESS: compare A and B in LISTEN_REFERENCE_36.html; older WAVs not changed')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Exception as e:
        log('STOP ' + repr(e))
        sys.exit(1)